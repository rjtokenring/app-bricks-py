"""Pytest configuration for the geniex-runner container tests.

Adds the container ``scripts`` directory to ``sys.path`` so make_store imports the same way it runs in the image.
"""

import os
import sys

SCRIPTS_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "scripts"))
if SCRIPTS_DIR not in sys.path:
    sys.path.insert(0, SCRIPTS_DIR)
